let currentLang = 'zh';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('cakeroll_lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // 截图内容本身是界面语言，按语言换图而不是靠文字翻译
    document.querySelectorAll('img[data-shot-zh]').forEach(el => {
        const src = el.getAttribute(lang === 'zh' ? 'data-shot-zh' : 'data-shot-en');
        const alt = el.getAttribute(lang === 'zh' ? 'data-alt-zh' : 'data-alt-en');
        if (src) el.setAttribute('src', src);
        if (alt) el.setAttribute('alt', alt);
    });

    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

    const langSelect = document.getElementById('langSelect');
    if (langSelect) {
        langSelect.value = lang;
    }
}

function initLanguage() {
    const savedLang = localStorage.getItem('cakeroll_lang');
    const detected = (navigator.language || 'en').toLowerCase().startsWith('zh') ? 'zh' : 'en';
    setLanguage(savedLang || detected);

    const langSelect = document.getElementById('langSelect');
    if (langSelect) {
        langSelect.addEventListener('change', (e) => setLanguage(e.target.value));
    }
}

document.addEventListener('DOMContentLoaded', initLanguage);